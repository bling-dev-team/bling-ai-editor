#!/usr/bin/env python3
"""Build a VO timeline in Resolve (no Python, no bridge) by generating a Lua script for
Workspace > Scripts and clicking it through macOS Accessibility. The readback is the
`Timeline:Export(path, 3)` xmeml file the script writes; parse it and compare against the plan.

Use this when Python scripting is not available inside Resolve (some free-edition builds list only
Lua entries under Workspace > Scripts, so the in-app bridge cannot start). Lua scripts in
`~/Library/Application Support/Blackmagic Design/DaVinci Resolve/Fusion/Scripts/Utility/` still run
from Workspace > Scripts with the whole API bound (`resolve` global). `io` and `os` are nil there, so
the plan is EMBEDDED in the generated Lua and the only file the script can write is a timeline export.

The invariants: create project, set the resolution and the fps, import the master,
CreateEmptyTimeline + AppendToTimeline with recordFrame = GetStartFrame() + rec (NEVER
CreateTimelineFromClips), video and audio as separate infos (then LINKED pairwise with
SetClipsLinked), SaveProject on the ProjectManager, then export the timeline as xmeml for readback.
The fps must be the one read from the AUDIO clip; plan frame counts are floor() maths, not round().

    python3 scripts/build_timeline_lua.py --job <job> --timeline "VO Cut v1" \
        --master raw/<job>_enhanced.mp4 --plan work/plan_v1.json [--fps 30] [--run]
"""
import argparse, json, subprocess, sys, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config  # noqa: E402

UTIL = Path.home() / "Library/Application Support/Blackmagic Design/DaVinci Resolve/Fusion/Scripts/Utility"
ROOT = Path(__file__).resolve().parent.parent


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen(job, project, timeline, master, plan, fps, width, height, export):
    infos = []
    for p in plan:
        for mt in (1, 2):
            infos.append(f"  {{mediaPoolItem=clip, startFrame={p['sf']}, endFrame={p['ef']}, mediaType={mt}, trackIndex=1, recordFrame=S+{p['rec']}}},")
    fps_s = str(int(fps)) if float(fps) == int(fps) else str(fps)
    return f"""-- generated by scripts/build_timeline_lua.py; do not edit by hand
local pm = resolve:GetProjectManager()
local cur = pm:GetCurrentProject()
if cur and cur:GetName() ~= "Untitled Project" and cur:GetName() ~= {lua_str(project)} then pm:SaveProject() end
local p = pm:GetCurrentProject()
if not p or p:GetName() ~= {lua_str(project)} then
  p = pm:CreateProject({lua_str(project)}) or (pm:LoadProject({lua_str(project)}) and pm:GetCurrentProject())
end
p:SetSetting("timelineResolutionWidth", "{width}")
p:SetSetting("timelineResolutionHeight", "{height}")
p:SetSetting("timelineFrameRate", "{fps_s}")
local mp = p:GetMediaPool(); local root = mp:GetRootFolder(); mp:SetCurrentFolder(root)
local clip = nil
for _, c in ipairs(root:GetClipList() or {{}}) do
  if c:GetClipProperty("File Path") == {lua_str(master)} then clip = c end
end
if not clip then
  local added = mp:ImportMedia({{{lua_str(master)}}})
  clip = added and added[1]
end
local clipfps = clip and clip:GetClipProperty("FPS") or "none"
for i = p:GetTimelineCount(), 1, -1 do
  local t = p:GetTimelineByIndex(i)
  if t and t:GetName() == {lua_str(timeline)} then mp:DeleteTimelines({{t}}) end   -- rebuild pre-review; never on a timeline a person has edited
end
local tl = mp:CreateEmptyTimeline({lua_str(timeline)})
p:SetCurrentTimeline(tl)
local S = tl:GetStartFrame()
local infos = {{
{chr(10).join(infos)}
}}
local out = mp:AppendToTimeline(infos)
-- video and audio are appended as SEPARATE infos, so they land UNLINKED and Cmd+B (blade) only
-- cuts the selected track. Link every V1 item to the A1 item at the same record position.
local _byPos = {{}}
for _, it in ipairs(tl:GetItemListInTrack("audio", 1) or {{}}) do _byPos[it:GetStart() .. ":" .. it:GetEnd()] = it end
for _, it in ipairs(tl:GetItemListInTrack("video", 1) or {{}}) do
  local m = _byPos[it:GetStart() .. ":" .. it:GetEnd()]
  if m then tl:SetClipsLinked({{it, m}}, true) end
end
pm:SaveProject()
-- the export is the readback AND the message channel: its name carries the clip fps and the append count
tl:Export({lua_str(export)} .. "__fps" .. tostring(clipfps) .. "__n" .. tostring(out and #out or -1) .. ".xml", 3)
"""


def click(name):
    r = subprocess.run(["osascript", "-e",
        f'tell application "System Events" to tell process "DaVinci Resolve" to click menu item "{name}" of menu 1 of menu item "Scripts" of menu 1 of menu bar item "Workspace" of menu bar 1'],
        capture_output=True, text=True)
    return r.returncode == 0, (r.stdout + r.stderr).strip()


def main():
    ap = argparse.ArgumentParser(description="Generate a Resolve Lua build script for a VO timeline "
                                             "(and optionally click it in Workspace > Scripts).")
    ap.add_argument("--job", required=True, help="job name (under paths.jobs_dir) or folder path")
    ap.add_argument("--project", default=config.get("resolve.project", "My Videos"),
                    help="Resolve project name (default resolve.project)")
    ap.add_argument("--timeline", required=True, help="timeline name to (re)build")
    ap.add_argument("--master", required=True, help="master clip, relative to the job")
    ap.add_argument("--plan", default="work/plan_v1.json", help="plan json [{sf,ef,rec,dur}], relative to the job")
    ap.add_argument("--fps", type=float, default=config.FPS, help="timeline fps (default video.fps)")
    ap.add_argument("--width", type=int, default=config.WIDTH)
    ap.add_argument("--height", type=int, default=config.HEIGHT)
    ap.add_argument("--name", default="editor_build", help="Scripts-menu entry name")
    ap.add_argument("--run", action="store_true", help="click it in Workspace > Scripts and wait for the export")
    a = ap.parse_args()
    job = config.job_dir(a.job)
    plan = json.load(open(job / a.plan))
    master = str((job / a.master).resolve())
    export = str(job / "work" / (a.timeline.replace(" ", "_") + "_readback"))
    lua = gen(job, a.project, a.timeline, master, plan, a.fps, a.width, a.height, export)
    target = UTIL / f"{a.name}.lua"
    target.write_text(lua)
    print("wrote", target, f"({len(plan)} segments, {sum(p['dur'] for p in plan)} frames)")
    if a.run:
        time.sleep(1)
        t0 = time.time()
        ok, msg = click(a.name)
        print("click:", ok, msg)
        for i in range(300):
            # only an export written AFTER the click counts: a stale file from the last run once
            # would pass as the readback of a rebuild and hide a plan change
            hits = sorted((h for h in job.glob("work/" + a.timeline.replace(" ", "_") + "_readback__*.xml") if h.stat().st_mtime > t0), key=lambda p: p.stat().st_mtime)
            if hits and time.time() - hits[-1].stat().st_mtime > 2:
                print("export:", hits[-1].name); return
            time.sleep(1)
        sys.exit("no export appeared in 300 s")


if __name__ == "__main__":
    main()
